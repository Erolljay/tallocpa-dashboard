import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import type { SourceDocument, WorksheetContext, WorksheetResult } from "../../types";
import { WITHHOLDING_FORMS } from "../withholding";
import { form0619E } from "./form-0619e";
import { form1601EQ } from "./form-1601eq";
import { branchFromTin, buildQapRows, qapCsv, qapDat, splitIndividualName, tin9 } from "./qap";
import { ewtLines, totalsByAtc } from "./ewt";

const doc = (over: Partial<SourceDocument>): SourceDocument => ({
  id: "x", docType: "bir_2307_issued", month: "2026-01-01", date: null, number: null,
  partyName: null, partyTin: null, partyAddress: null,
  vatable: 0, vatExempt: 0, zeroRated: 0, vat: 0, total: 0, atc: null, withholding: 0,
  ...over,
});

/** The quarter used for the QAP fixture (generated by taxify's exporter: __fixtures__/generate-qap-fixture.mjs). */
const Q1: SourceDocument[] = [
  doc({ id: "j1", month: "2026-01-01", date: "2026-01-15", number: "A-1", partyName: "ACME Services Corp", partyTin: "111-222-333-00000", atc: "WC158", total: 10000000, withholding: 100000 }),
  doc({ id: "f1", month: "2026-02-01", date: "2026-02-10", number: "A-2", partyName: "ACME Services Corp", partyTin: "111-222-333-00000", atc: "WC158", total: 5000000, withholding: 50000 }),
  doc({ id: "f2", month: "2026-02-01", date: "2026-02-28", number: "R-1", partyName: "ACME Services Corp", partyTin: "111222333-00000", atc: "WC100", total: 3000000, withholding: 150000 }),
  doc({ id: "m1", month: "2026-03-01", date: "2026-03-05", number: "P-9", partyName: "DELA CRUZ, JUAN", partyTin: "444-555-666", atc: "WI010", total: 2000000, withholding: 100000 }),
  doc({ id: "m2", month: "2026-03-01", date: "2026-03-20", number: "B-1", partyName: "Beta Lessor Co.", partyTin: "777-888-999-001", atc: "WC100", total: 1000000, withholding: 50000 }),
  // Not a 2307 issued: ignored by the withholding forms.
  doc({ id: "s1", docType: "bir_2307_received", month: "2026-03-01", partyName: "Customer", partyTin: "999-999-999", atc: "WC158", total: 100, withholding: 1 }),
  doc({ id: "p1", docType: "purchase_receipt", month: "2026-03-01", total: 5000 }),
];

const client: WorksheetContext["client"] = {
  id: "c1", name: "Tallo Test Trading, Inc.", tin: "123-456-789-00000", rdoCode: "074", registeredAddress: "Iloilo City",
  taxpayerType: "corporation", fiscalYearEndMonth: 12, vatRegistered: true,
};

function ctx(form: string, periodStart: string, periodEnd: string, documents: SourceDocument[], over: Partial<WorksheetContext> = {}): WorksheetContext {
  return {
    client,
    filing: { id: "f", form, periodLabel: form === "1601-EQ" ? "Q1 2026" : periodStart.slice(0, 7), periodStart, periodEnd, dueDate: "2026-04-30" },
    documents,
    inputs: {},
    priorFigures: {},
    ...over,
  };
}

const lineMap = (r: WorksheetResult) => Object.fromEntries(r.sections.flatMap((s) => s.lines).map((l) => [l.line, l.amount]));
const byKey = (r: WorksheetResult) => Object.fromEntries(r.sections.flatMap((s) => s.lines).map((l) => [l.key, l.amount]));

describe("registry entries", () => {
  it("cover 0619-E, 1601-EQ and 1604-E (1601-C and 1604-C are the payroll module's)", () => {
    expect(WITHHOLDING_FORMS.flatMap((m) => m.forms)).toEqual(["0619-E", "1601-EQ", "1604-E"]);
  });
});

describe("EWT lines from 2307s issued", () => {
  it("groups by ATC, sorted, with base and tax withheld summed", () => {
    const { lines, errors, warnings } = ewtLines(Q1);
    expect(errors).toEqual([]);
    expect(warnings).toEqual([]);
    expect(totalsByAtc(lines)).toEqual([
      { atc: "WC100", desc: "Rentals - property/personal", rate: 5, base: 4000000, withheld: 200000, count: 2 },
      { atc: "WC158", desc: "Top WA supplier - goods", rate: 1, base: 15000000, withheld: 150000, count: 2 },
      { atc: "WI010", desc: "Professional fees, <=3M", rate: 5, base: 2000000, withheld: 100000, count: 1 },
    ]);
  });

  it("blocks a 2307 without TIN or ATC, and warns on an unknown ATC", () => {
    const { lines, errors, warnings } = ewtLines([
      doc({ id: "a", number: "1", partyName: "No TIN", atc: "WC158", total: 100000, withholding: 1000 }),
      doc({ id: "b", number: "2", partyName: "No ATC", partyTin: "111-222-333", total: 100000, withholding: 1000 }),
      doc({ id: "c", number: "3", partyName: "Short TIN", partyTin: "1234", atc: "WC158", total: 100000, withholding: 1000 }),
      doc({ id: "d", number: "4", partyName: "Odd", partyTin: "111-222-333", atc: "WZ999", total: 100000, withholding: 2000 }),
    ]);
    expect(errors).toHaveLength(3);
    expect(errors[0]).toMatch(/no payee TIN/);
    expect(errors[1]).toMatch(/no ATC/);
    expect(errors[2]).toMatch(/not 9 digits/);
    expect(warnings).toHaveLength(1);
    expect(warnings[0]).toMatch(/WZ999 is not in the ATC table/);
    expect(lines).toEqual([expect.objectContaining({ atc: "WZ999", known: false, rate: 2, base: 100000, withheld: 2000 })]);
  });

  it("grosses up a missing income payment, computes a missing tax withheld and flags a mismatch", () => {
    const { lines, warnings } = ewtLines([
      doc({ id: "a", partyTin: "111-222-333", atc: "WC158", withholding: 1000 }),
      doc({ id: "b", partyTin: "111-222-333", atc: "WC011", total: 1000000 }),
      doc({ id: "c", partyTin: "111-222-333", atc: "WC010", total: 1000000, withholding: 50000 }),
    ]);
    expect(lines.map((l) => [l.base, l.withheld])).toEqual([[100000, 1000], [1000000, 150000], [1000000, 50000]]);
    expect(warnings).toHaveLength(3);
    expect(warnings[2]).toMatch(/is not 10% of 10,000.00/);
  });
});

describe("0619-E", () => {
  it("remits the month's tax withheld, items 14 to 18", () => {
    const c = ctx("0619-E", "2026-02-01", "2026-02-28", Q1.filter((d) => d.month === "2026-02-01"));
    const r = form0619E.compute(c);
    expect(r.errors).toEqual([]);
    expect(lineMap(r)).toMatchObject({ "14": 200000, "15": 0, "16": 200000, "17A": 0, "17B": 0, "17C": 0, "17D": 0, "18": 200000 });
    expect(r.documentIds).toEqual(["f1", "f2"]);
    const bg = r.sections[0].lines;
    expect(bg.map((l) => [l.line, l.basis])).toEqual([
      ["5", "WME10"], ["6", "WE"], ["7", "123-456-789"], ["8", "074"], ["9", "Tallo Test Trading, Inc."], ["10", "Iloilo City"],
    ]);
    expect(r.schedules[0].rows.map((x) => x.atc)).toEqual(["WC100", "WC158"]);
    expect(r.sections[1].lines.find((l) => l.line === "18")?.emphasis).toBe("payable");
  });

  it("takes an amended return's earlier remittance and penalties from the inputs", () => {
    const c = ctx("0619-E", "2026-02-01", "2026-02-28", Q1.filter((d) => d.month === "2026-02-01"), {
      inputs: { previously_remitted: "500.00", surcharge: "₱125.00", interest: "10", compromise: "" },
    });
    const r = form0619E.compute(c);
    expect(lineMap(r)).toMatchObject({ "14": 200000, "15": 50000, "16": 150000, "17A": 12500, "17B": 1000, "17C": 0, "17D": 13500, "18": 163500 });
  });

  it("rejects bad inputs and a client without TIN/RDO", () => {
    const r = form0619E.compute({ ...ctx("0619-E", "2026-02-01", "2026-02-28", [], { inputs: { surcharge: "abc", interest: "-5" } }), client: { ...client, tin: null, rdoCode: null } });
    expect(r.errors).toEqual([
      "The client has no TIN on file. Add it on the client's page.",
      "The client has no RDO code on file. Add it on the client's page.",
      "Surcharge: enter an amount like 1,234.56.",
      "Interest: enter zero or more.",
    ]);
  });

  it("says when there is nothing to remit", () => {
    const r = form0619E.compute(ctx("0619-E", "2026-02-01", "2026-02-28", []));
    expect(r.warnings).toEqual(["No approved 2307s issued in this month: the remittance is zero."]);
    expect(lineMap(r)["18"]).toBe(0);
  });
});

describe("1601-EQ", () => {
  const prior = {
    "0619-E@2026-01": { amount_of_remittance: 100000 },
    "0619-E@2026-02": { amount_of_remittance: 200000 },
  };

  it("lists each ATC as items 13+, totals at 19 and deducts the 0619-E remittances", () => {
    const r = form1601EQ.compute(ctx("1601-EQ", "2026-01-01", "2026-03-31", Q1, { priorFigures: prior }));
    expect(r.errors).toEqual([]);
    const atcLines = r.sections[1].lines.slice(0, 3);
    expect(atcLines.map((l) => [l.line, l.key, l.amount])).toEqual([
      ["13", "atc_WC100", 200000],
      ["14", "atc_WC158", 150000],
      ["15", "atc_WI010", 100000],
    ]);
    expect(atcLines[0].basis).toBe("Tax base 40,000.00 at 5%");
    expect(byKey(r)).toMatchObject({
      total_taxes_withheld: 450000,
      remitted_month1: 100000,
      remitted_month2: 200000,
      previously_filed: 0,
      prior_over_remittance: 0,
      other_payments: 0,
      total_remittances: 300000,
      tax_still_due: 150000,
      surcharge: 0,
      interest: 0,
      compromise: 0,
      total_penalties: 0,
      total_amount_due: 150000,
    });
    expect(lineMap(r)).toMatchObject({ "19": 450000, "20": 100000, "21": 200000, "25": 300000, "26": 150000, "30": 0, "31": 150000 });
    expect(r.documentIds).toEqual(["j1", "f1", "f2", "m1", "m2"]);
    // The payee without branch digits in the TIN is flagged for the QAP.
    expect(r.warnings).toEqual([expect.stringMatching(/^QAP — DELA CRUZ, JUAN: no branch code/)]);
  });

  it("uses typed remittances and adjustments, and can end in an over-remittance", () => {
    const r = form1601EQ.compute(
      ctx("1601-EQ", "2026-01-01", "2026-03-31", Q1, {
        priorFigures: prior,
        inputs: { remitted_month1: "1,000", previously_filed: "100", prior_over_remittance: "3,000", other_payments: "50", surcharge: "25" },
      }),
    );
    expect(byKey(r)).toMatchObject({ remitted_month1: 100000, remitted_month2: 200000, total_remittances: 615000, tax_still_due: -165000, total_penalties: 2500, total_amount_due: -162500 });
    expect(r.sections[1].lines.find((l) => l.key === "remitted_month1")?.basis).toMatch(/Typed in/);
  });

  it("warns when a month has 2307s but no 0619-E worksheet, or the 0619-E differs", () => {
    const r = form1601EQ.compute(ctx("1601-EQ", "2026-01-01", "2026-03-31", Q1, { priorFigures: { "0619-E@2026-02": { amount_of_remittance: 150000 } } }));
    expect(byKey(r).remitted_month1).toBe(0);
    expect(r.warnings).toContain("No 0619-E worksheet for January 2026. If a 0619-E was filed, enter the amount remitted for month 1.");
    expect(r.warnings.some((w) => /February 2026: the 0619-E remitted 1,500.00 but the approved 2307s for that month total 2,000.00/.test(w))).toBe(true);
  });

  it("moves ATCs beyond six to an attachment", () => {
    const atcs = ["WC010", "WC020", "WC030", "WC040", "WC050", "WC060", "WC100"];
    const docs = atcs.map((atc, i) => doc({ id: `d${i}`, partyTin: "111-222-333-0000", partyName: `P${i}`, atc, total: 100000, withholding: 10000 }));
    const r = form1601EQ.compute(ctx("1601-EQ", "2026-01-01", "2026-03-31", docs));
    expect(r.sections[1].lines.slice(0, 7).map((l) => l.line)).toEqual(["13", "14", "15", "16", "17", "18", "Attach."]);
    expect(r.warnings.filter((w) => /7 ATCs this quarter/.test(w))).toHaveLength(1);
  });

  it("offers the QAP as DAT and CSV", () => {
    const c = ctx("1601-EQ", "2026-01-01", "2026-03-31", Q1, { priorFigures: prior });
    const att = form1601EQ.attachments!(c, form1601EQ.compute(c));
    expect(att.map((a) => a.kind)).toEqual(["qap-dat", "qap-csv"]);
    expect(att[0].build().fileName).toBe("1234567890000032026" + "1601EQ.DAT");
  });
});

describe("QAP", () => {
  const lines = ewtLines(Q1).lines;
  const agent = { tin: client.tin, rdoCode: client.rdoCode, name: client.name };

  it("builds payee × ATC rows with the three months, sorted by name then ATC", () => {
    const rows = buildQapRows(lines, "2026-01-01");
    expect(rows.map((r) => [r.name, r.atc, r.branchCode, r.months.map((m) => m.withheld)])).toEqual([
      ["ACME Services Corp", "WC100", "0000", [0, 150000, 0]],
      ["ACME Services Corp", "WC158", "0000", [100000, 50000, 0]],
      ["Beta Lessor Co.", "WC100", "0001", [0, 0, 50000]],
      ["DELA CRUZ, JUAN", "WI010", null, [0, 0, 100000]],
    ]);
    expect(rows[3].individual).toEqual({ lastName: "DELA CRUZ", firstName: "JUAN", middleName: "" });
  });

  it("writes the DAT exactly as taxify's exportQAPDat does", () => {
    const expected = readFileSync(path.join(import.meta.dirname, "__fixtures__", "qap-q1-2026.DAT"), "utf8");
    const file = qapDat(buildQapRows(lines, "2026-01-01"), agent, "2026-01-01");
    expect(file.body).toBe(expected);
    expect(file.fileName).toBe("12345678900000320261601EQ.DAT");
  });

  it("writes the Excel layout as CSV", () => {
    const file = qapCsv(buildQapRows(lines, "2026-01-01"), agent, "2026-01-01", "Q1 (Jan–Mar) 2026");
    expect(file.fileName).toBe("QAP_1601EQ_Q1__Jan_Mar__2026.csv");
    const rows = file.body.replace(/^﻿/, "").split("\r\n");
    expect(rows[0]).toBe("Attachment to BIR Form 1601-EQ");
    expect(rows[2]).toBe('"FOR THE QUARTER ENDING MARCH, 2026"');
    expect(rows[3]).toBe("TIN : 123-456-789-0000");
    expect(rows[4]).toBe(`"WITHHOLDING AGENT'S NAME: TALLO TEST TRADING, INC."`);
    expect(rows[8]).toBe(`1,111-222-333-0000,${"ACME SERVICES CORP".padEnd(50)},${"".padEnd(50)},WC100,Rentals - property/personal,0.00,5,0.00,30000.00,5,1500.00,0.00,5,0.00,30000.00,1500.00`);
    expect(rows[11]).toBe(`4,444-555-666-0001,,"${"DELA CRUZ, JUAN".padEnd(50)}",WI010,"Professional fees, <=3M",0.00,5,0.00,0.00,5,0.00,20000.00,5,1000.00,20000.00,1000.00`);
    expect(rows[12]).toBe(",,,,,Grand Total :,,,,,,,,,,210000.00,4500.00");
    expect(rows.slice(13)).toEqual(["------------------", "==================", "END OF REPORT", ""]);
  });

  it("helpers follow taxify", () => {
    expect(tin9("123-45")).toBe("123450000");
    expect(tin9(null)).toBe("000000000");
    expect(branchFromTin("123-456-789-00001")).toBe("0001");
    expect(branchFromTin("123-456-789-000")).toBe("0000");
    expect(branchFromTin("123456789")).toBeNull();
    expect(splitIndividualName("Santos, Maria Cruz", "WI100")).toEqual({ lastName: "Santos", firstName: "Maria Cruz", middleName: "" });
    expect(splitIndividualName("Santos, Maria", "WC100")).toBeNull();
    expect(splitIndividualName("Maria Santos", "WI100")).toBeNull();
  });
});

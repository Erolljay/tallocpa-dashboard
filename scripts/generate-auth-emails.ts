/**
 * Writes Supabase's sign-in email templates in the firm's layout to supabase/templates/.
 * Run `pnpm email:auth-templates`, then paste each file into Supabase → Authentication →
 * Emails → Templates (the subject is in supabase/templates/README.md).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { authEmailTemplates } from "../src/lib/email/auth-templates";

const dir = path.resolve(import.meta.dirname, "..", "supabase", "templates");
mkdirSync(dir, { recursive: true });
const templates = authEmailTemplates();
for (const t of templates) writeFileSync(path.join(dir, t.file), t.html);

const readme = [
  "# Sign-in email templates",
  "",
  "Generated by `pnpm email:auth-templates` from src/lib/email/auth-templates.ts. Do not edit by hand.",
  "",
  "Paste each file into Supabase → Authentication → Emails → Templates, with its subject:",
  "",
  "| Dashboard template | Subject | File |",
  "| --- | --- | --- |",
  ...templates.map((t) => `| ${t.dashboardName} | ${t.subject} | \`${t.file}\` |`),
  "",
].join("\n");
writeFileSync(path.join(dir, "README.md"), readme);
console.log(`Wrote ${templates.length} templates to ${dir}`);
